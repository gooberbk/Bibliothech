export function getBookById(id: string): Book | undefined {
  return books.find((book) => book.id === id)
}

export function getRelatedBooks(book: Book, limit: number = 4): Book[] {
  return books
    .filter((b) => b.id !== book.id && b.category === book.category)
    .slice(0, limit)
}
